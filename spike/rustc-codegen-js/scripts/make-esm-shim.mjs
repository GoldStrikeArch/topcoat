// Derives the ES module form of the runtime shim from runtime/shim.js.
//
//   node scripts/make-esm-shim.mjs <out.js>
//
// runtime/shim.js is a plain script: it assigns `globalThis.__rt`, it is
// concatenated ahead of a compiled program, and pages load it with a bare
// `<script src>` and extend the object afterwards (demo/index.html and
// demo-app/src/glue.js both do). A program compiled with
// `-Cllvm-args=js-modules=esm` needs the same members as an ES module instead,
// so that `import * as __rt from "./shim.js"` binds them.
//
// One file cannot be both -- an `export` is a syntax error in a script -- so
// there is one source and one derived artifact, never two hand written copies.
// The artifact is the shim's own text with an export clause appended:
//
//   <runtime/shim.js, verbatim>
//   export const { js_log_i32, ..., bytes_str_tagged } = globalThis.__rt;
//
// The names in that clause are not a list anybody maintains. The script is
// evaluated here and the clause is written out of the keys of the `__rt` it
// actually built, so a member added to the shim is exported by the next run and
// the two forms cannot drift.
//
// The emitted call sites are the same either way: a namespace import binds
// `__rt.alloc(...)` exactly as the global did.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const shimPath = path.resolve(here, "..", "runtime", "shim.js");

const out = process.argv[2];
if (!out) {
  console.error("usage: make-esm-shim.mjs <out.js>");
  process.exit(2);
}

const source = readFileSync(shimPath, "utf8");

// Evaluated rather than parsed: the members are whatever the script installs,
// which is the only definition of them that cannot go stale. `new Function`
// runs it with this process's globals, so anything the shim reaches for at load
// time (TextEncoder, TextDecoder) is there, and a member that needs something
// absent fails here, loudly, instead of at run time in a test.
const members = new Function(`${source}\nreturn globalThis.__rt;`)();

const names = Object.keys(members).sort();
if (names.length === 0) {
  console.error("make-esm-shim.mjs: runtime/shim.js installed no members on `__rt`");
  process.exit(1);
}

for (const name of names) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) {
    console.error(`make-esm-shim.mjs: \`${name}\` is not a plain identifier, so it cannot be exported`);
    process.exit(1);
  }
}

const clause = [
  "",
  "// ---------------------------------------------------------------------------",
  "// Generated by scripts/make-esm-shim.mjs. Do not edit: everything above this",
  "// line is runtime/shim.js verbatim, and the names below are the members that",
  "// file installed on `__rt`.",
  "// ---------------------------------------------------------------------------",
  "",
  `export const {\n${names.map((name) => `  ${name},`).join("\n")}\n} = globalThis.__rt;`,
  "",
].join("\n");

writeFileSync(out, source + clause);

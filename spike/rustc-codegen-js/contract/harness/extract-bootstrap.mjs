// Extract solid's hydration bootstrap script by DRIVING generateHydrationScript
// with a sentinel event name, then lifting the sentinel into a placeholder.
//
//   node --import ./register-loader.mjs extract-bootstrap.mjs
//
// Writes fixtures/hydration-script.js.
//
// The extraction is driven rather than copied: we call the real function with
// eventNames ["__TOPCOAT_EVENTS__"], locate that sentinel in the output, and
// replace it with a ${EVENTS} placeholder. Then we prove the round trip -- that
// substituting a real event list into our template reproduces what solid emits
// for that same list, byte for byte -- for several event lists including the
// full 22 delegated events.

import { writeText, writeJson, provenance, SOLID, FIXTURES } from "./paths.mjs";
import { readFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const server = await import(pathToFileURL(path.join(SOLID, "web", "dist", "server.js")).href);
const { generateHydrationScript } = server;

const SENTINEL = "__TOPCOAT_EVENTS__";

// Drive with one sentinel event and lift the sentinel out from BETWEEN the
// quotes solid supplies. solid's source is:
//
//   ["${eventNames.join('", "')}"]
//
// so the quotes are part of the template, not part of the substituted value.
// The placeholder must sit inside them or the round trip diverges on the empty
// list -- see $emptyListQuirk below.
const driven = generateHydrationScript({ eventNames: [SENTINEL] });
if (!driven.includes(`"${SENTINEL}"`)) {
  throw new Error(
    `sentinel not found in generateHydrationScript output -- the interpolation shape changed:\n${driven}`
  );
}

const template = driven.replace(SENTINEL, "${EVENTS}");

// Same, for the nonce variant, so the contract records both shapes.
const drivenNonce = generateHydrationScript({ eventNames: [SENTINEL], nonce: "__NONCE__" });
const templateNonce = drivenNonce.replace(SENTINEL, "${EVENTS}").replace("__NONCE__", "${NONCE}");

/**
 * Render our extracted template for an event list, exactly as solid would:
 * join with '", "' and let the template supply the surrounding quotes.
 */
function render(eventNames) {
  return template.replace("${EVENTS}", eventNames.join('", "'));
}

// ------------------------------------------------------------- round trip
const delegated = JSON.parse(
  readFileSync(path.join(FIXTURES, "delegated-events.json"), "utf8")
).events;

const roundTrips = [];
for (const [label, list] of [
  ["solid default", ["click", "input"]],
  ["single", ["click"]],
  ["empty", []],
  ["all 22 delegated", delegated]
]) {
  const ours = render(list);
  const theirs = generateHydrationScript({ eventNames: list });
  roundTrips.push({ label, eventCount: list.length, byteIdentical: ours === theirs });
  if (ours !== theirs) {
    console.error(`round trip FAILED for ${label}`);
    console.error(`  ours:   ${ours}`);
    console.error(`  theirs: ${theirs}`);
    process.exit(1);
  }
}

// ------------------------------------------------------------- the artifact
const eventsLine = delegated.join('", "');

const out = `// EXTRACTED ARTIFACT -- do not edit by hand.
//
// Generated by contract/harness/extract-bootstrap.mjs from
// solid-js@${JSON.parse(readFileSync(path.join(SOLID, "package.json"), "utf8")).version}
// web/dist/server.js:621 generateHydrationScript().
//
// WHAT THIS IS
// ------------
// The bootstrap <script> solid emits into SSR'd HTML. It runs BEFORE any
// framework code loads, and its only job is to capture events that fire on
// server-rendered markup during the window between first paint and hydration,
// so they can be replayed once the component that owns them is alive.
//
// It installs a global \`_$HY\`:
//
//   {
//     events:    [],             // captured [element, event] pairs, replayed
//                                //   by runHydrationEvents()
//     completed: new WeakSet,    // elements already hydrated -- events on
//                                //   these are NOT captured (they have real
//                                //   listeners now)
//     r:         {},             // resource/resolved-data registry. INERT in
//                                //   this build: written by the streaming SSR
//                                //   path, read by resource hydration. An
//                                //   emitter that does no streaming leaves it
//                                //   empty, but the KEY MUST EXIST -- solid's
//                                //   client reads _$HY.r unconditionally.
//     fe() {}                    // "flush events" hook. A no-op stub here;
//                                //   the streaming path replaces it. Again,
//                                //   must exist as a callable.
//   }
//
// Note there is NO \`done\` field in the initial shape -- it is assigned later
// by the client runtime, not by this bootstrap.
//
// The capture listener walks up from the event target to the nearest ancestor
// carrying \`data-hk\`, crossing shadow boundaries via \`.host\`. That walk is
// why data-hk on template roots is load-bearing: it is the hydration owner
// lookup for replayed events.
//
// The trailing \`<!--xs-->\` marker terminates the script section for solid's
// streaming parser.
//
// BUILD NOTE
// ----------
// \${EVENTS} sits INSIDE the quotes the template already supplies, mirroring
// solid's own \`["\${eventNames.join('", "')}"]\`. Substitute the event names
// joined with the three-character sequence \`", "\` -- do NOT quote them
// yourself. For click+input the substituted value is exactly:  click", "input
//
// QUIRK -- an empty event list does NOT produce \`[]\`. Because the quotes are
// part of the template, an empty join yields \`[""]\`: solid registers a
// document listener for the empty-string event name. Harmless, but it means
// "capture nothing" is not expressible through eventNames; omit the script.
//
// IMPORTANT -- solid's default is NOT the delegated-events set. solid defaults
// eventNames to ["click", "input"] (TWO events). The 22 events in
// fixtures/delegated-events.json are what dom-expressions DELEGATES at runtime,
// which is a different and larger set. Whoever emits this script chooses the
// list; capturing all 22 costs 22 document listeners during the pre-hydration
// window. See CONTRACT-DOM.md.

/** The bootstrap template. \${EVENTS} takes a pre-quoted, comma-joined list. */
export const BOOTSTRAP_TEMPLATE = ${JSON.stringify(template)};

/** The same, with a \${NONCE} slot for a CSP nonce attribute value. */
export const BOOTSTRAP_TEMPLATE_NONCE = ${JSON.stringify(templateNonce)};

/** The 22 delegated events, joined for substitution into \${EVENTS}. */
export const DELEGATED_EVENTS_LIST = ${JSON.stringify(eventsLine)};

/** solid's own default event list, joined for substitution into \${EVENTS}. */
export const SOLID_DEFAULT_EVENTS_LIST = ${JSON.stringify('click", "input')};

/**
 * Build the bootstrap script for an event list.
 *
 * @param {string[]} eventNames events to capture before hydration
 * @param {string} [nonce] CSP nonce for the <script> tag
 * @returns {string} the full <script>...</script><!--xs--> string
 */
export function buildHydrationScript(eventNames, nonce) {
  const list = eventNames.join('", "');
  return nonce === undefined
    ? BOOTSTRAP_TEMPLATE.replace("\${EVENTS}", list)
    : BOOTSTRAP_TEMPLATE_NONCE.replace("\${EVENTS}", list).replace("\${NONCE}", nonce);
}
`;

writeText("hydration-script.js", out);

writeJson("hydration-script.meta.json", {
  ...provenance("extract-bootstrap.mjs"),
  $source: "solid-js/web/dist/server.js:621 generateHydrationScript",
  solidDefaultEventNames: ["click", "input"],
  delegatedEventCount: delegated.length,
  $defaultIsNotDelegatedSet:
    "solid's generateHydrationScript defaults to 2 events (click, input); the " +
    "dom-expressions DelegatedEvents set has 22. These are different mechanisms: " +
    "the bootstrap captures pre-hydration events, delegation dispatches post-hydration.",
  hyShape: {
    events: "array of [element, event] captured before hydration",
    completed: "WeakSet of already-hydrated elements (excluded from capture)",
    r: "resource registry -- inert {} in the non-streaming build, key must exist",
    fe: "flush-events hook -- no-op stub, must exist as a callable",
    $noDoneField: "the initial shape has NO 'done' field; the client assigns it later"
  },
  trailingMarker: "<!--xs-->",
  ownerLookup:
    "walks up from composedPath()[0] (falling back to event.target) to the nearest " +
    "ancestor with a data-hk attribute, hopping shadow roots via .host",
  roundTrips
});

console.log(`hydration-script.js  extracted, ${roundTrips.length} round trips byte-identical`);
console.log(`  solid default eventNames: ["click", "input"] (2) -- NOT the 22 delegated events`);
console.log(`  _$HY = { events: [], completed: WeakSet, r: {}, fe(){} }  (no 'done' field)`);
